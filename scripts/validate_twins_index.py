#!/usr/bin/env python3
"""Check twins/index.json against the twins/ tree, the catalogue and twins/README.md.

The index restates, for every immediate directory under twins/, what that
directory and its catalogue records already say: kind, status, achieved
fidelity, independent evidence, blockers, owner artefact and open issues. This
check refuses an index that has drifted from its sources:

- a directory under twins/ with no entry, or an entry whose directory is gone;
- a catalogue twin record that no entry accounts for, or that two entries claim;
- a twin record or part record that cites twins/<dir>/ but is missing from that
  directory's entry, or a listed record that is not linked to the directory;
- a fidelity, validation status or archived flag that differs from the record;
- a directory without a twin record that declares a fidelity level, or gives no
  reason for having no record;
- a physical correlation claimed without a physically_correlated record;
- an active entry with no open issue, a study entry with one, or an archived
  entry that its owner artefact and docs/ARCHIVE.md do not declare archived;
- a missing owner artefact or evidence path;
- a generated table in twins/README.md that no longer matches the index.

It checks consistency, never engineering: a passing index qualifies no part.

  python3 scripts/validate_twins_index.py           # check
  python3 scripts/validate_twins_index.py --write   # regenerate the README table
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
INDEX = Path("twins/index.json")
README = Path("twins/README.md")
BEGIN = "<!-- twins-index:begin (generated by scripts/validate_twins_index.py --write; do not edit) -->"
END = "<!-- twins-index:end -->"
ISSUES_URL = "https://github.com/cluster2600/porscheparts/issues/"
ENTRY_KEYS = {
    "directory", "kind", "status", "scope", "fidelity", "physical_correlation",
    "records", "part_ids", "no_record_reason", "independent_evidence", "blockers",
    "owner_artefact", "evidence", "issues",
}
OPTIONAL_KEYS = {"fidelity_note"}
RECORD_KEYS = {"twin_id", "fidelity", "validation_status", "archived"}
NO_FIDELITY = "none_declared"
ARCHIVED = re.compile(r"\barchived\b", re.IGNORECASE)


def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def load_records(root: Path, folder: str, key: str) -> dict[str, tuple[Path, dict]]:
    records: dict[str, tuple[Path, dict]] = {}
    for path in sorted((root / folder).glob("*.json")):
        data = load_json(path)
        if isinstance(data, dict) and isinstance(data.get(key), str):
            records[data[key]] = (path.relative_to(root), data)
    return records


def cites_directory(record: dict, directory: str) -> bool:
    return f"twins/{directory}/" in json.dumps(record, ensure_ascii=False)


def twin_dirs(root: Path) -> list[str]:
    return sorted(p.name for p in (root / "twins").iterdir() if p.is_dir() and not p.name.startswith("."))


def relative(target: str) -> str:
    """Link from twins/README.md to a repository-relative path."""
    return target[len("twins/"):] if target.startswith("twins/") else f"../{target}"


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def issue_links(issues: list[int]) -> str:
    return ", ".join(f"[#{n}]({ISSUES_URL}{n})" for n in issues) or "none open"


def render(index: dict, twins: dict, parts: dict) -> str:
    """Render the generated block of twins/README.md from the index."""
    lines = [BEGIN, "", "### Status, fidelity and records", "",
             "| directory | kind | status | achieved fidelity | catalogue records | open issues |",
             "|---|---|---|---|---|---|"]
    for e in index["directories"]:
        records = []
        for r in e["records"]:
            path = twins.get(r["twin_id"], (Path(""),))[0].as_posix()
            mark = " (archived record)" if r["archived"] else ""
            records.append(f"[`{r['twin_id']}`]({relative(path)}){mark}")
        for pid in e["part_ids"]:
            path = parts.get(pid, (Path(""),))[0].as_posix()
            records.append(f"part [`{pid}`]({relative(path)})")
        fidelity = f"`{e['fidelity']}`" if e["fidelity"] != NO_FIDELITY else "none declared"
        lines.append(
            f"| [`{e['directory']}/`]({e['directory']}/) | {e['kind'].replace('_', ' ')} "
            f"| {e['status']} | {fidelity} | {'<br>'.join(records) or 'no record'} | {issue_links(e['issues'])} |")
    lines += ["", "### Scope, independent evidence and blockers", "",
              "| directory | scope and variant | independent evidence | blockers | owner artefact |", "|---|---|---|---|---|"]
    for e in index["directories"]:
        scope = e["scope"] + (f". {e['fidelity_note'][0].upper()}{e['fidelity_note'][1:]}" if e.get("fidelity_note") else "")
        lines.append(f"| `{e['directory']}/` | {cell(scope)} | {cell(e['independent_evidence'])} "
                     f"| {cell('; '.join(e['blockers']) or 'none recorded')} "
                     f"| [`{e['owner_artefact']}`]({relative(e['owner_artefact'])}) |")
    lines += ["", "### Directories without a twin record, and why", "", "| directory | reason |", "|---|---|"]
    for e in index["directories"]:
        if not e["records"]:
            lines.append(f"| `{e['directory']}/` | {cell(e['no_record_reason'])} |")
    lines += ["", "### Twin records without a directory", "", "| record | reason | open issues |", "|---|---|---|"]
    for r in index["records_without_directory"]:
        path = twins.get(r["twin_id"], (Path(""),))[0].as_posix()
        lines.append(f"| [`{r['twin_id']}`]({relative(path)}) | {cell(r['reason'])} | {issue_links(r['issues'])} |")
    lines += ["", END]
    return "\n".join(lines)


def check_issues(where: str, issues: Any, errors: list[str]) -> None:
    if not isinstance(issues, list) or any(not isinstance(n, int) or isinstance(n, bool) or n < 1 for n in issues):
        errors.append(f"{where}: issues must be a list of positive issue numbers")
    elif issues != sorted(set(issues)):
        errors.append(f"{where}: issues must be sorted and unique")


def validate(root: Path = ROOT, index: dict | None = None, readme: str | None = None,
             directories: list[str] | None = None) -> list[str]:
    errors: list[str] = []
    index = load_json(root / INDEX) if index is None else index
    readme = (root / README).read_text(encoding="utf-8") if readme is None else readme
    directories = twin_dirs(root) if directories is None else directories
    twins = load_records(root, "catalog/twins", "twin_id")
    parts = load_records(root, "catalog/parts", "part_id")
    kinds, statuses = set(index.get("kinds", {})), set(index.get("statuses", {}))
    archive_doc = (root / "docs/ARCHIVE.md").read_text(encoding="utf-8")
    entries = index.get("directories", [])

    names = [e.get("directory") for e in entries]
    if names != sorted(names):
        errors.append("directories must be sorted by name")
    for name in sorted(set(directories) - set(names)):
        errors.append(f"twins/{name}/ has no entry in {INDEX}")
    for name in sorted(set(names) - set(directories)):
        errors.append(f"entry {name}: twins/{name}/ does not exist")
    for name in sorted({n for n in names if names.count(n) > 1}):
        errors.append(f"entry {name}: listed more than once")

    claimed: dict[str, list[str]] = {}
    for e in entries:
        name = e.get("directory", "?")
        where = f"entry {name}"
        missing, unknown = ENTRY_KEYS - set(e), set(e) - ENTRY_KEYS - OPTIONAL_KEYS
        if missing or unknown:
            errors.append(f"{where}: missing keys {sorted(missing)}, unknown keys {sorted(unknown)}")
            continue
        if e["kind"] not in kinds:
            errors.append(f"{where}: kind {e['kind']!r} is not defined in kinds")
        if e["status"] not in statuses:
            errors.append(f"{where}: status {e['status']!r} is not defined in statuses")
        for key in ("scope", "independent_evidence"):
            if not isinstance(e[key], str) or not e[key].strip():
                errors.append(f"{where}: {key} must be a non-empty sentence")
        if not isinstance(e["blockers"], list) or not all(isinstance(b, str) and b for b in e["blockers"]):
            errors.append(f"{where}: blockers must be a list of strings")
        for path in [e["owner_artefact"], *e["evidence"]]:
            if not (root / path).exists():
                errors.append(f"{where}: path {path} does not exist")
        check_issues(where, e["issues"], errors)

        records = e["records"]
        for r in records:
            if set(r) != RECORD_KEYS:
                errors.append(f"{where}: record entry needs exactly {sorted(RECORD_KEYS)}")
                continue
            claimed.setdefault(r["twin_id"], []).append(name)
            if r["twin_id"] not in twins:
                errors.append(f"{where}: twin record {r['twin_id']} is not in catalog/twins")
                continue
            path, rec = twins[r["twin_id"]]
            owner = (root / e["owner_artefact"]).read_text(encoding="utf-8") if (root / e["owner_artefact"]).is_file() else ""
            if not (cites_directory(rec, name) or r["twin_id"] in owner or path.stem in owner):
                errors.append(f"{where}: {r['twin_id']} neither cites twins/{name}/ nor is named by {e['owner_artefact']}")
            if r["fidelity"] != rec.get("fidelity"):
                errors.append(f"{where}: {r['twin_id']} fidelity is {rec.get('fidelity')!r} in its record, not {r['fidelity']!r}")
            status = rec.get("validation", {}).get("status")
            if r["validation_status"] != status:
                errors.append(f"{where}: {r['twin_id']} validation status is {status!r} in its record, not {r['validation_status']!r}")
            if r["archived"] != bool(ARCHIVED.search(rec.get("name", ""))):
                errors.append(f"{where}: {r['twin_id']} archived flag disagrees with its record name")
        for tid, (path, rec) in twins.items():
            if cites_directory(rec, name) and tid not in {r.get("twin_id") for r in records}:
                errors.append(f"{where}: {tid} ({path.as_posix()}) cites twins/{name}/ but is not listed")

        listed_fidelities = {r.get("fidelity") for r in records}
        if records:
            if e["fidelity"] not in listed_fidelities:
                errors.append(f"{where}: fidelity {e['fidelity']!r} is not the level of a listed record")
            if e["no_record_reason"] is not None:
                errors.append(f"{where}: no_record_reason must be null when a twin record is listed")
        else:
            if e["fidelity"] != NO_FIDELITY:
                errors.append(f"{where}: no twin record, so fidelity must be {NO_FIDELITY!r}, not {e['fidelity']!r}")
            if not isinstance(e["no_record_reason"], str) or not e["no_record_reason"].strip():
                errors.append(f"{where}: no twin record and no no_record_reason")
        correlated = any(r.get("validation_status") == "physically_correlated" for r in records)
        if (e["physical_correlation"] != "none" or e["kind"] == "physical_twin") and not correlated:
            errors.append(f"{where}: physical correlation claimed without a physically_correlated twin record")

        record_text = "".join(json.dumps(twins[r["twin_id"]][1]) for r in records if r.get("twin_id") in twins)
        owner_text = (root / e["owner_artefact"]).read_text(encoding="utf-8") if (root / e["owner_artefact"]).is_file() else ""
        for pid in e["part_ids"]:
            if pid not in parts:
                errors.append(f"{where}: part {pid} is not in catalog/parts")
                continue
            path, rec = parts[pid]
            if not (cites_directory(rec, name) or pid in record_text or pid.lower() in owner_text or pid in owner_text):
                errors.append(f"{where}: part {pid} is not linked to twins/{name}/ by its record, a listed twin record or the owner artefact")
        for pid, (path, rec) in parts.items():
            if cites_directory(rec, name) and pid not in e["part_ids"]:
                errors.append(f"{where}: part {pid} ({path.as_posix()}) cites twins/{name}/ but is not listed")

        if e["status"] == "active" and not e["issues"]:
            errors.append(f"{where}: active entries must link at least one open issue")
        if e["status"] == "study" and e["issues"]:
            errors.append(f"{where}: study entries have no open issue; mark it active")
        if (e["status"] == "archived") != (e["kind"] == "archived_reference"):
            errors.append(f"{where}: status archived and kind archived_reference go together")
        if e["status"] == "archived" and not (ARCHIVED.search(owner_text) and f"twins/{name}/" in archive_doc):
            errors.append(f"{where}: archived, but {e['owner_artefact']} or docs/ARCHIVE.md does not say so")

    for r in index.get("records_without_directory", []):
        tid = r.get("twin_id")
        claimed.setdefault(tid, []).append("records_without_directory")
        check_issues(f"record {tid}", r.get("issues"), errors)
        if tid not in twins:
            errors.append(f"record {tid}: not in catalog/twins")
        if not isinstance(r.get("reason"), str) or not r["reason"].strip():
            errors.append(f"record {tid}: a record without a directory needs a reason")
        if not (root / r.get("owner_artefact", "")).is_file():
            errors.append(f"record {tid}: owner artefact {r.get('owner_artefact')} does not exist")
    for tid in sorted(twins):
        where = claimed.get(tid, [])
        if not where:
            errors.append(f"twin record {tid} is not accounted for in {INDEX}")
        elif len(where) > 1:
            errors.append(f"twin record {tid} is claimed by {', '.join(where)}")

    if not errors:
        expected = render(index, twins, parts)
        start, stop = readme.find(BEGIN), readme.find(END)
        if start < 0 or stop < 0:
            errors.append(f"{README}: generated block markers are missing; run --write")
        elif readme[start:stop + len(END)] != expected:
            errors.append(f"{README}: generated table is stale; run python3 scripts/validate_twins_index.py --write")
    return errors


def write(root: Path = ROOT) -> None:
    index = load_json(root / INDEX)
    block = render(index, load_records(root, "catalog/twins", "twin_id"), load_records(root, "catalog/parts", "part_id"))
    text = (root / README).read_text(encoding="utf-8")
    start, stop = text.find(BEGIN), text.find(END)
    if start < 0 or stop < 0:
        raise SystemExit(f"{README}: insert the markers {BEGIN!r} and {END!r} first")
    (root / README).write_text(text[:start] + block + text[stop + len(END):], encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="regenerate the table in twins/README.md")
    args = parser.parse_args()
    if args.write:
        write()
    errors = validate()
    for error in errors:
        print(f"ERROR {error}", file=sys.stderr)
    if errors:
        return 1
    index = load_json(ROOT / INDEX)
    print(f"twins index: {len(index['directories'])} directories and "
          f"{len(index['records_without_directory'])} directory-less record(s) reconciled")
    return 0


if __name__ == "__main__":
    sys.exit(main())
