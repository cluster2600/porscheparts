#!/usr/bin/env python3
"""Render the public catalogue (ROADMAP Phase 4) from the catalogue records.

Two pages are generated in `docs/catalogue/`:

- `README.md`, the public catalogue: only records that pass the publication
  gate below. Today no record passes, and the page says so instead of
  showing anything.
- `STATUS.md`, a clearly labelled status listing of every other record. Each
  entry leads with "Not ready to print" and states the reasons the gate
  refuses it. It is a study register, not a catalogue.

The publication gate is deliberately the top of the validation ladder of
`catalog/schemas/part.schema.json` (see docs/QUALITY_GATES.md): a record is
published only when

1. `validation.status` is `released` (the validator already refuses a released
   additive part without all eleven AM steps passed, and a released critical
   part without reviewer, evidence and inspection);
2. `validation.evidence` is not empty;
3. `validation.reviewed_by` and `validation.reviewed_on` are filled;
4. its public images exist: `parts/<id>/media/preview.json` with
   `preview.png`, and its `kind` is not a `status_card`.

Each published entry carries a version: the SHA-256 of its record, and of its
preview images as recorded in `preview.json`, so a reader can tell which
revision of the part a page describes. Values are copied from the record,
never summarized.

    python3 scripts/render_public_catalogue.py --write
    python3 scripts/render_public_catalogue.py --check
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from render_parts_table import nom  # noqa: E402

FICHES = ROOT / "catalog" / "parts"
OUT = ROOT / "docs" / "catalogue"
ENTETE = "<!-- generated by scripts/render_public_catalogue.py - do not edit by hand -->"
GATE_STATUS = "released"


def media_info(part_id: str) -> dict | None:
    manifest = ROOT / "parts" / part_id.lower() / "media" / "preview.json"
    if not manifest.exists():
        return None
    return json.loads(manifest.read_text(encoding="utf-8"))


def gate_failures(fiche: dict) -> list[str]:
    """Reasons a record is refused publication; empty means it passes."""
    v = fiche.get("validation", {})
    raisons = []
    if v.get("status") != GATE_STATUS:
        raisons.append(f"validation status `{v.get('status')}`, not `{GATE_STATUS}`")
    if not v.get("evidence"):
        raisons.append("no validation evidence")
    if not v.get("reviewed_by") or not v.get("reviewed_on"):
        raisons.append("no recorded reviewer and review date")
    info = media_info(fiche["part_id"])
    if info is None or not (ROOT / "parts" / fiche["part_id"].lower() / "media" / "preview.png").exists():
        raisons.append("no public preview images")
    elif info.get("kind") == "status_card":
        raisons.append("public image is a status card, not part geometry")
    return raisons


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def charger() -> list[tuple[Path, dict]]:
    fiches = [(c, json.loads(c.read_text(encoding="utf-8"))) for c in sorted(FICHES.glob("*.json"))]
    return sorted(fiches, key=lambda x: x[1]["part_id"])


def cell(x) -> str:
    return str(x).replace("|", "\\|").replace("\n", " ")


def catalogue(fiches) -> str:
    publiees = [(c, f) for c, f in fiches if not gate_failures(f)]
    out = [ENTETE, "", "# Public catalogue", "",
           "Generated from `catalog/parts/*.json`. Only parts that pass the publication "
           f"gate appear here: validation status `{GATE_STATUS}`, linked evidence, a recorded "
           "reviewer and review date, and public part images. See "
           "[QUALITY_GATES.md](../QUALITY_GATES.md) and [SAFETY.md](../SAFETY.md).", ""]
    if not publiees:
        out += [f"**No part has passed the publication gate.** {len(fiches)} records are "
                "studies; they are listed, labelled not ready to print, in "
                "[STATUS.md](STATUS.md).", ""]
        return "\n".join(out)
    out += ["| part | name | safety class | record version | images | evidence |",
            "|---|---|---|---|---|---|"]
    for c, f in publiees:
        pid = f["part_id"]
        info = media_info(pid) or {}
        imgs = ", ".join(f"[{n}](../../parts/{pid.lower()}/media/{n}) `{h[:12]}`"
                         for n, h in sorted(info.get("image_sha256", {}).items()))
        out.append(f"| [{pid}](../parts/{pid.lower()}.md) | {cell(nom(f))} | "
                   f"{f['classification'].get('safety_class')} | `{sha(c)[:12]}` | {imgs} | "
                   f"{cell(', '.join(f['validation']['evidence']))} |")
    out += ["", f"{len(publiees)} of {len(fiches)} records published.", ""]
    return "\n".join(out)


def statut(fiches) -> str:
    refusees = [(c, f, gate_failures(f)) for c, f in fiches if gate_failures(f)]
    out = [ENTETE, "", "# Study status listing: not ready to print", "",
           "**Nothing on this page is a catalogue part.** Every record below is refused by "
           "the publication gate of the [public catalogue](README.md). None is "
           "dimensionally accurate, fitted, tested or released, and none may be printed "
           "or fitted to a vehicle. Images, where present, show concept geometry or a "
           "status card, never a manufactured part.", "",
           f"{len(refusees)} records.", "",
           "| part | name | status | safety class | why it is not published |",
           "|---|---|---|---|---|"]
    for _, f, raisons in refusees:
        pid = f["part_id"]
        out.append(f"| [{pid}](../parts/{pid.lower()}.md) | **Not ready to print.** "
                   f"{cell(nom(f))} | `{f['validation'].get('status')}` | "
                   f"{f['classification'].get('safety_class')} | {cell('; '.join(raisons))} |")
    return "\n".join(out + [""])


def attendues() -> dict[Path, str]:
    fiches = charger()
    return {OUT / "README.md": catalogue(fiches), OUT / "STATUS.md": statut(fiches)}


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    pages = attendues()
    if a.write:
        OUT.mkdir(parents=True, exist_ok=True)
        for chemin, texte in pages.items():
            chemin.write_text(texte, encoding="utf-8", newline="\n")
        print(f"docs/catalogue: {len(pages)} pages written")
        return 0
    bad = [c for c, t in pages.items() if not c.exists() or c.read_text(encoding="utf-8") != t]
    for c in bad:
        print(f"FAIL   catalogue page missing or stale: {c.relative_to(ROOT)}", file=sys.stderr)
    if bad:
        print("       rerun: python3 scripts/render_public_catalogue.py --write", file=sys.stderr)
        return 1
    print("OK   docs/catalogue matches the catalogue records and the publication gate")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
