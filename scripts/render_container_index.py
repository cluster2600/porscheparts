#!/usr/bin/env python3
"""Generate docs/CONTAINER_INDEX.md: every container recipe, its lock and its workflows.

``containers/README.md`` describes the main images by hand. This index is
generated, so it cannot fall behind: it lists **every** Dockerfile under
``containers/``, the lock file (``containers/*.lock.json``) that names it, the
image repository and status that the lock records, and the GitHub workflows
that build it. A recipe with no lock is shown as unlocked; that is a fact about
the recipe, not a judgement of it.

The recipes, locks and workflows are only read. Nothing here edits a pinned
file.

    python3 scripts/render_container_index.py --write   # regenerate
    python3 scripts/render_container_index.py --check   # fail if stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTAINERS = ROOT / "containers"
WORKFLOWS = ROOT / ".github" / "workflows"
OUTPUT = ROOT / "docs" / "CONTAINER_INDEX.md"


def recipes() -> list[Path]:
    found = []
    for path in CONTAINERS.rglob("*"):
        if not path.is_file() or path.name.endswith(".dockerignore"):
            continue
        if path.name == "Dockerfile" or path.name.startswith("Dockerfile.") or path.name.endswith(".Dockerfile"):
            found.append(path)
    return sorted(found, key=lambda p: p.relative_to(ROOT).as_posix())


def purpose(path: Path) -> str:
    """First plain comment line of the recipe, ignoring parser directives."""
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if not stripped.startswith("#"):
            break
        text = stripped.lstrip("#").strip()
        if not text or re.match(r"^(syntax|escape|check)\s*=", text, re.I):
            continue
        return text if len(text) <= 110 else text[:107].rstrip() + "..."
    return ""


def lock_records() -> list[tuple[str, dict, str]]:
    out = []
    for path in sorted(CONTAINERS.glob("*.lock.json")):
        text = path.read_text(encoding="utf-8")
        out.append((path.relative_to(ROOT).as_posix(), json.loads(text), text))
    return out


def image_of(lock: dict) -> tuple[str, str]:
    image = lock.get("image") if isinstance(lock.get("image"), dict) else lock.get("planned_image")
    repository = image.get("repository", "") if isinstance(image, dict) else ""
    digest = image.get("digest") if isinstance(image, dict) else None
    status = lock.get("status") or ""
    if not status and isinstance(lock.get("verification"), dict):
        status = lock["verification"].get("status", "")
    if not status:
        status = "digest pinned" if digest else "no digest recorded"
    return repository, str(status)


def workflow_texts() -> list[tuple[str, str]]:
    return [(p.relative_to(ROOT).as_posix(), p.read_text(encoding="utf-8"))
            for p in sorted(WORKFLOWS.glob("*.yml"))]


def render() -> str:
    locks = lock_records()
    flows = workflow_texts()
    rows = []
    counts = {"recipes": 0, "locked": 0, "built_by_workflow": 0}
    for recipe in recipes():
        rel = recipe.relative_to(ROOT).as_posix()
        counts["recipes"] += 1
        matching = [(name, data) for name, data, text in locks if rel in text]
        workflows = [name for name, text in flows if rel in text]
        if matching:
            counts["locked"] += 1
        if workflows:
            counts["built_by_workflow"] += 1
        lock_cell = "<br/>".join(f"[`{Path(n).name}`](../{n})" for n, _ in matching) or "unlocked"
        image_cell = "<br/>".join(f"`{image_of(d)[0]}`" for _, d in matching if image_of(d)[0]) or "—"
        status_cell = "<br/>".join(image_of(d)[1] for _, d in matching) or "—"
        flow_cell = "<br/>".join(f"[`{Path(n).name}`](../{n})" for n in workflows) or "—"
        note = purpose(recipe).replace("|", "\\|")
        rows.append(f"| [`{rel.removeprefix('containers/')}`](../{rel}) | {note} | {lock_cell} | {image_cell} | {status_cell} | {flow_cell} |")
    head = [
        "# Container index",
        "",
        "<!-- Generated by scripts/render_container_index.py; do not edit by hand. -->",
        "",
        "Every container recipe under [`containers/`](../containers/), with the lock",
        "file that names it, the image repository and status that lock records, and",
        "the GitHub workflows that build it. The hand-written overview of the main",
        "images is [containers/README.md](../containers/README.md); how to build,",
        "verify and rent them is in [COMPUTE_ENVIRONMENT.md](COMPUTE_ENVIRONMENT.md).",
        "",
        f"**{counts['recipes']} recipes**, {counts['locked']} named by a lock file,"
        f" {counts['built_by_workflow']} built by a workflow. \"Unlocked\" means no",
        "`containers/*.lock.json` names the recipe; such an image has no pinned",
        "digest in the repository and must not be cited as evidence by tag alone.",
        "Recipes, locks and their recipe inputs are pinned: never edit them to change",
        "this page (see AGENTS.md).",
        "",
        "| Recipe | Purpose (first comment line of the recipe, quoted as written; pinned recipes may still be French) | Lock | Image | Lock status | Workflows |",
        "|---|---|---|---|---|---|",
    ]
    return "\n".join(head + rows) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.write:
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
        return 0
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
        print(f"FAIL {OUTPUT.relative_to(ROOT)} is stale; run: python3 scripts/render_container_index.py --write")
        return 1
    print(f"OK   {OUTPUT.relative_to(ROOT)} lists every container recipe")
    return 0


if __name__ == "__main__":
    sys.exit(main())
